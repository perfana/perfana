import { BadRequestException } from '@nestjs/common';
import { plainToInstance } from 'class-transformer';
import { validate } from 'class-validator';
import { normalizeConfluenceParentPages } from './systems-under-test.service';
import { UpdateSystemUnderTestDto } from './dto/update-system-under-test.dto';

const CFG = '22222222-2222-2222-2222-222222222222';

describe('normalizeConfluenceParentPages', () => {
  it('stores each path as "A / B", lowercases the connection id and drops an empty path', () => {
    expect(normalizeConfluenceParentPages({ [CFG.toUpperCase()]: ' Perf /MyApp/ ', '33333333-3333-3333-3333-333333333333': ' / ' }))
      .toEqual({ [CFG]: 'Perf / MyApp' });
  });

  /*
   * Generated by the /ship test coverage audit (pass 2).
   * Value: protects=PATCH refuses a confluence_parent_pages that is not an object before the service sees it;
   *   fails_when=@IsObject is dropped, so a string reaches Object.entries and stores per-character keys or 500s;
   *   why_new=the normalizer tests call the function directly, past the DTO; seam=none;
   *   no_claim=the global ValidationPipe options (class-validator run directly; unit only)
   */
  it.each([['a string', 'Performance / MyApp'], ['an array', ['Performance']]])('the DTO refuses %s for the map', async (_n, value) => {
    const errors = await validate(plainToInstance(UpdateSystemUnderTestDto, { confluence_parent_pages: value }));
    expect(errors.map((e) => e.property)).toEqual(['confluence_parent_pages']);
    expect(await validate(plainToInstance(UpdateSystemUnderTestDto, { confluence_parent_pages: { [CFG]: 'A' } }))).toEqual([]);
  });

  it.each([
    [{ 'not-a-uuid': 'A' }],
    [{ [CFG]: 42 }],
    [{ [CFG]: Array.from({ length: 11 }, (_, i) => `L${i}`).join('/') }],
    [{ [CFG]: 'x'.repeat(256) }],
  ])('refuses %j', (raw) => {
    expect(() => normalizeConfluenceParentPages(raw as Record<string, unknown>)).toThrow(BadRequestException);
  });
});
