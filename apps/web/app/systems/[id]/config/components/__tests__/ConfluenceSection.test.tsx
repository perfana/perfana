import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import ConfluenceSection from '../ConfluenceSection';
import { fetchConfluenceConfigs } from '@/lib/confluence';
import { updateSystemUnderTest } from '@/lib/systems';

jest.mock('@/lib/confluence', () => ({ fetchConfluenceConfigs: jest.fn() }));
jest.mock('@/lib/systems', () => ({ updateSystemUnderTest: jest.fn() }));

const CFG = '22222222-2222-2222-2222-222222222222';
const FOREIGN = '33333333-3333-3333-3333-333333333333';

const system = {
  id: 'sut-1',
  name: 'MyApp',
  organization_id: 'org-1',
  confluence_parent_pages: { [CFG]: 'Old', [FOREIGN]: 'Kept' },
};

beforeEach(() => {
  (fetchConfluenceConfigs as jest.Mock).mockResolvedValue([
    { id: CFG, label: 'Wiki', spaceKey: 'PERF', parentPageId: '77' },
  ]);
  (updateSystemUnderTest as jest.Mock).mockImplementation(async (_id, dto) => dto);
});

it("lists the organization's connections and saves the path normalized, keeping entries for other connections", async () => {
  const onUpdate = jest.fn();
  render(<ConfluenceSection systemUnderTest={system} onUpdate={onUpdate} />);

  const field = await screen.findByLabelText('Wiki (space PERF)');
  expect(fetchConfluenceConfigs).toHaveBeenCalledWith('org-1');
  const save = screen.getByRole('button', { name: /save/i });
  expect(save).toBeDisabled();

  fireEvent.change(field, { target: { value: ' Performance /MyApp/ ' } });
  fireEvent.click(save);

  await waitFor(() => expect(updateSystemUnderTest).toHaveBeenCalledWith('sut-1', {
    confluence_parent_pages: { [CFG]: 'Performance / MyApp', [FOREIGN]: 'Kept' },
  }));
  expect(onUpdate).toHaveBeenCalledWith(expect.objectContaining({ name: 'MyApp', confluence_parent_pages: { [CFG]: 'Performance / MyApp', [FOREIGN]: 'Kept' } }));
});

/*
 * Generated by the /ship test coverage audit (pass 1).
 * Value: protects=a refused save shows the API's message, leaves the page's system untouched and lets the user retry;
 *   fails_when=the catch is dropped (unhandled rejection, no message), onUpdate runs on failure, or saving never resets;
 *   why_new=both existing tests resolve the save; seam=none; no_claim=real API error shapes (mocked lib/systems; unit only)
 */
it('shows the error and keeps the form editable when the save is refused', async () => {
  (updateSystemUnderTest as jest.Mock).mockRejectedValueOnce(new Error('confluence_parent_pages: at most 10 levels'));
  const onUpdate = jest.fn();
  render(<ConfluenceSection systemUnderTest={system} onUpdate={onUpdate} />);
  fireEvent.change(await screen.findByLabelText('Wiki (space PERF)'), { target: { value: 'A / B' } });
  fireEvent.click(screen.getByRole('button', { name: /save/i }));

  expect(await screen.findByText('confluence_parent_pages: at most 10 levels')).toBeInTheDocument();
  expect(onUpdate).not.toHaveBeenCalled();
  expect(screen.getByRole('button', { name: /save/i })).toBeEnabled();
});

/*
 * Generated by the /ship test coverage audit (pass 2).
 * Value: protects=a failed connection list shows its message, and an org with none shows the Integrations hint, with no fields or Save;
 *   fails_when=the load catch or the empty-list branch is removed (endless spinner or a bare card);
 *   why_new=every test resolves with one connection; seam=none; no_claim=real API error shapes (mocked lib/confluence; unit only)
 */
it.each([
  ['the load error', () => (fetchConfluenceConfigs as jest.Mock).mockRejectedValueOnce(new Error('Forbidden (403)')), 'Forbidden (403)'],
  ['the no-connection hint', () => (fetchConfluenceConfigs as jest.Mock).mockResolvedValueOnce([]), /has no Confluence connection/],
] as const)('shows %s instead of the form', async (_name, arrange, text) => {
  arrange();
  render(<ConfluenceSection systemUnderTest={system} onUpdate={jest.fn()} />);
  expect(await screen.findByText(text)).toBeInTheDocument();
  expect(screen.queryByRole('button', { name: /save/i })).not.toBeInTheDocument();
  expect(screen.queryByRole('progressbar')).not.toBeInTheDocument();
});

it('clears an entry when the field is emptied', async () => {
  render(<ConfluenceSection systemUnderTest={system} onUpdate={jest.fn()} />);
  fireEvent.change(await screen.findByLabelText('Wiki (space PERF)'), { target: { value: '  ' } });
  fireEvent.click(screen.getByRole('button', { name: /save/i }));
  await waitFor(() => expect(updateSystemUnderTest).toHaveBeenCalledWith('sut-1', { confluence_parent_pages: { [FOREIGN]: 'Kept' } }));
});
