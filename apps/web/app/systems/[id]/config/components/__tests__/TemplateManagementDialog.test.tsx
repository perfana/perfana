import React from 'react';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import '@testing-library/jest-dom';
import TemplateManagementDialog from '../TemplateManagementDialog';
import { getTemplate } from '@/lib/api/reports';

jest.mock('@/lib/api/reports', () => ({
  ...jest.requireActual('@/lib/api/reports'),
  getTemplate: jest.fn(),
}));

describe('TemplateManagementDialog', () => {
  // Value: protects=a template stored with its array out of `order` lists and saves in `order`,
  // which is what the report renders by, even when the section builder is never opened;
  // fails_when=the load stops sorting; why_new=nothing rendered this dialog, and the builder's own
  // sort never runs on this path; seam=getTemplate; no_claim=how a template came to be stored out
  // of order
  it('lists and saves a stored template in its order values', async () => {
    (getTemplate as jest.Mock).mockResolvedValue({
      name: 'Nightly',
      description: '',
      is_default: false,
      sections: [
        { type: 'slo', order: 1 },
        { type: 'header', order: 0 },
      ],
    });
    const onSubmit = jest.fn().mockResolvedValue(undefined);

    render(
      <TemplateManagementDialog
        open
        isEdit
        template={{ id: 'template-1' } as never}
        systemId="system-1"
        systemName="Webshop"
        testEnvironment="acc"
        workload="loadTest"
        onSubmit={onSubmit}
        onClose={jest.fn()}
        loading={false}
      />,
    );

    await screen.findByText('2 section(s) configured');
    expect(screen.getAllByText(/^(header|slo)$/).map((el) => el.textContent)).toEqual(['header', 'slo']);

    fireEvent.click(screen.getByRole('button', { name: 'Update' }));
    await waitFor(() => expect(onSubmit).toHaveBeenCalled());
    expect(onSubmit.mock.calls[0][2].map((s: { type: string }) => s.type)).toEqual(['header', 'slo']);
  });

  // Generated by /ship test coverage audit.
  // Value: protects=what the real section builder saves shows in this dialog's list, reaches the
  // save renumbered, and is what the builder reopens on; fails_when=handleSectionsConfigured drops
  // the result, or the builder stops being seeded from this dialog's sections; why_new=the test
  // above never opens the builder, and the builder's own tests stop at onTemplateBuilt; seam=none;
  // no_claim=a drop (added by click; jsdom has no layout) or the API's save (getTemplate is mocked)
  it('takes what the section builder saves, and reopens the builder on it', async () => {
    (getTemplate as jest.Mock).mockResolvedValue({
      name: 'Nightly',
      description: '',
      is_default: false,
      sections: [
        { type: 'slo', order: 1 },
        { type: 'header', order: 0 },
      ],
    });
    const onSubmit = jest.fn().mockResolvedValue(undefined);

    render(
      <TemplateManagementDialog
        open
        isEdit
        template={{ id: 'template-1' } as never}
        systemId="system-1"
        systemName="Webshop"
        testEnvironment="acc"
        workload="loadTest"
        onSubmit={onSubmit}
        onClose={jest.fn()}
        loading={false}
      />,
    );
    await screen.findByText('2 section(s) configured');

    fireEvent.click(screen.getByRole('button', { name: 'Edit Sections' }));
    fireEvent.click(await screen.findByLabelText('Add Apdex Scores section'));
    fireEvent.click(screen.getByRole('button', { name: 'Save Configuration' }));

    await screen.findByText('3 section(s) configured');
    expect(screen.getAllByText(/^(header|slo|apdex)$/).map((el) => el.textContent)).toEqual(['header', 'slo', 'apdex']);

    fireEvent.click(screen.getByRole('button', { name: 'Edit Sections' }));
    await screen.findByLabelText('Add Apdex Scores section');
    // Delete buttons are the canvas cards: one each, in a builder mounted anew for this open.
    expect(screen.getAllByTestId('DeleteIcon')).toHaveLength(3);
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }));
    await waitFor(() => expect(screen.queryByLabelText('Add Apdex Scores section')).not.toBeInTheDocument());

    fireEvent.click(screen.getByRole('button', { name: 'Update' }));
    await waitFor(() => expect(onSubmit).toHaveBeenCalled());
    expect(onSubmit.mock.calls[0][2]).toEqual([
      { type: 'header', order: 0 },
      { type: 'slo', order: 1 },
      { type: 'apdex', order: 2 },
    ]);
  });
});
