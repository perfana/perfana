// Lives OUTSIDE src/database/migrations for the same reason as consolidated-schema-split.spec.ts:
// that directory is globbed as migrations, and a compiled *.spec.js there gets require()d as one.
import { QueryRunner } from 'typeorm';
import {
  CompareTemplateOwnership1822000000000,
  COMPARE_TEMPLATE_KEY_SQL,
} from '../migrations/1822000000000-CompareTemplateOwnership';

const run = async (dir: 'up' | 'down', firstResult: unknown = []): Promise<string[]> => {
  const out: string[] = [];
  const runner = {
    query: async (q: string) => {
      out.push(q);
      return out.length === 1 ? firstResult : [];
    },
  } as unknown as QueryRunner;
  const m = new CompareTemplateOwnership1822000000000();
  await (dir === 'up' ? m.up(runner) : m.down(runner));
  return out;
};

describe('CompareTemplateOwnership (1822)', () => {
  it('checks for rows the new key rejects BEFORE any DDL', async () => {
    // Numbered above 1791, so on a fresh install there is no batch transaction to roll back a
    // half-applied run. The check has to come first and touch nothing.
    const sql = await run('up');
    expect(sql[0]).toMatch(/^\s*SELECT 'duplicate key'/);
    expect(sql[0]).not.toMatch(/ALTER|CREATE|UPDATE/);
    expect(sql[0]).toContain(`GROUP BY ${COMPARE_TEMPLATE_KEY_SQL}`);
    expect(sql[0]).toMatch(/panel_id IS NULL AND panel_title IS NULL/);
  });

  it('throws naming the ids, and runs nothing after the check', async () => {
    const out: string[] = [];
    const runner = {
      query: async (q: string) => {
        out.push(q);
        return [{ kind: 'duplicate key', ids: ['id-old', 'id-new'] }];
      },
    } as unknown as QueryRunner;

    await expect(new CompareTemplateOwnership1822000000000().up(runner)).rejects.toThrow(
      /duplicate key: id-old, id-new.*safe to re-run/,
    );
    expect(out).toHaveLength(1);
  });

  it('every statement after the check is safe to repeat', async () => {
    const [, ...rest] = await run('up');
    const ddl = rest.filter((q) => /ALTER TABLE|CREATE/.test(q));
    expect(ddl.length).toBeGreaterThan(0);
    for (const q of ddl) {
      expect(q).toMatch(/IF NOT EXISTS/);
    }
    // The two backfills only touch rows they have not touched yet.
    const updates = rest.filter((q) => /^\s*UPDATE/.test(q));
    expect(updates).toHaveLength(2);
    expect(updates[0]).toMatch(/AND read_only IS NOT TRUE/);
    // Only provisioning's own rows become read-only, or the first boot prunes hand-made ones.
    expect(updates[0]).toMatch(/created_by = 'system:provisioning'/);
    expect(updates[1]).toMatch(/NOT \(COALESCE\(config_overrides, '\{\}'::jsonb\) \? 'higherIsBetter'\)/);
  });

  /**
   * Generated by /ship test coverage audit.
   * Value: protects=a fresh install keeps migrating past 1822: nothing in up() or down() opens a
   *   SAVEPOINT, which is a hard 25P01 once 1791's COMMIT has ended the batch transaction;
   * fails_when=a statement is isolated with SAVEPOINT/RELEASE instead of a plpgsql EXCEPTION block;
   * why_new=cagg-refresh-windows.spec.ts pins this rule for 1799 only, and TODOS.md says nothing pins
   *   it for later migrations;
   * seam=none;
   * no_claim=that the SQL runs on Postgres (recorded queries; unit only)
   */
  it('opens no SAVEPOINT in either direction, since it runs after 1791 ends the batch transaction', async () => {
    const sql = [...(await run('up')), ...(await run('down'))].join('\n');
    expect(sql).not.toMatch(/\bSAVEPOINT\b/i);
  });

  it('scopes the backfills and the index to template rows, never classify-metric rows', async () => {
    const [, ...rest] = await run('up');
    for (const q of rest.filter((s) => /UPDATE|CREATE UNIQUE INDEX/.test(s))) {
      expect(q).toMatch(/system_under_test_id IS NULL/);
    }
  });

  it('scopes both pre-check arms to template rows, as the index is', async () => {
    // Without it classify-metric rows (one per workload on the same panel) read as duplicates and
    // the migration refuses to deploy.
    const [check] = await run('up');
    expect(check.match(/WHERE system_under_test_id IS NULL/g)).toHaveLength(2);
  });

  it('leaves read_only nullable, so an older SUT bundle still imports', async () => {
    // The importer's json_populate_recordset yields NULL, not the default, for a missing key.
    const sql = (await run('up')).join('\n');
    expect(sql).toMatch(/ADD COLUMN IF NOT EXISTS read_only boolean DEFAULT false'?/);
    expect(sql).not.toMatch(/read_only boolean NOT NULL/);
  });

  it('puts the previous lock_timeout back on both exit paths', async () => {
    // set_config(..., true) outlives the DO block for the rest of the batch transaction.
    for (const q of (await run('up')).filter((s) => /set_config\('lock_timeout', '3s', true\)/.test(s))) {
      expect(q).toMatch(/prev_lock_timeout text := current_setting\('lock_timeout'\)/);
      expect(q.match(/set_config\('lock_timeout', prev_lock_timeout, true\)/g)).toHaveLength(2);
    }
  });

  it('indexes the same key the pre-check groups by', async () => {
    const sql = (await run('up')).join('\n');
    expect(sql).toContain(
      `CREATE UNIQUE INDEX IF NOT EXISTS uq_provisioned_template_ds_compare_configs_key\nON public.provisioned_template_ds_compare_configs (${COMPARE_TEMPLATE_KEY_SQL}`,
    );
  });

  it('adds the CHECK that closes the NULL panel term', async () => {
    const sql = (await run('up')).join('\n');
    expect(sql).toMatch(
      /CHECK \(system_under_test_id IS NOT NULL OR panel_id IS NOT NULL OR panel_title IS NOT NULL\)/,
    );
  });

  it('adds both provenance columns to ds_compare_config with no foreign key', async () => {
    const sql = (await run('up')).join('\n');
    expect(sql).toMatch(/ALTER TABLE public\.ds_compare_config ADD COLUMN IF NOT EXISTS template_id uuid NULL/);
    expect(sql).toMatch(/ALTER TABLE public\.ds_compare_config ADD COLUMN IF NOT EXISTS template_base jsonb NULL/);
    expect(sql).not.toMatch(/REFERENCES/);
  });

  it('takes table locks with a bounded wait', async () => {
    const [, ...rest] = await run('up');
    for (const q of rest.filter((s) => /ALTER TABLE|CREATE UNIQUE INDEX/.test(s))) {
      expect(q).toMatch(/set_config\('lock_timeout', '3s', true\)/);
    }
  });

  it('down() drops everything up() added', async () => {
    const sql = (await run('down')).join('\n');
    expect(sql).toMatch(/DROP COLUMN IF EXISTS template_base/);
    expect(sql).toMatch(/DROP COLUMN IF EXISTS template_id/);
    expect(sql).toMatch(/DROP INDEX IF EXISTS public\.uq_provisioned_template_ds_compare_configs_key/);
    expect(sql).toMatch(/DROP CONSTRAINT IF EXISTS ck_provisioned_template_ds_compare_configs_panel/);
    expect(sql).toMatch(/DROP COLUMN IF EXISTS read_only/);
  });
});
